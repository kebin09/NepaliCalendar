function hashString(str) {
  let h = 0;
  for (let i = 0; i < str.length; i += 1) {
    h = (Math.imul(31, h) + str.charCodeAt(i)) | 0;
  }
  return Math.abs(h) || 1;
}

function seededRandom(seed) {
  let t = seed % 2147483647;
  if (t <= 0) t += 2147483646;
  return function next() {
    t = (t * 16807) % 2147483647;
    return (t - 1) / 2147483646;
  };
}

function pick(rng, arr) {
  return arr[Math.floor(rng() * arr.length)];
}

export function getDailyRashifal({ year, month, day }) {
  return RASHIS.map((r, i) => {
    const rng = seededRandom(hashString(`${year}-${month}-${day}-${i}`));
    return {
      name: r.name,
      sign: r.sign,
      text: `${pick(rng, OVERALL)} ${pick(rng, CAREER)} ${pick(rng, HEALTH)} ${pick(rng, MONEY)} ${pick(rng, LOVE)}`,
      luckyNumber: Math.floor(rng() * 9) + 1,
      luckyColor: pick(rng, COLORS),
      luckyDay: pick(rng, DAYS),
    };
  });
}
