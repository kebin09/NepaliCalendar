export const BS_MIN_YEAR = 2000;
export const BS_MAX_YEAR = 2100;

const EPOCH_AD = { year: 1943, month: 4, day: 14 };

const DEV_DIGITS = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"];

export function toDev(value) {
  return String(value).replace(/\d/g, (d) => DEV_DIGITS[Number(d)]);
}

export function daysInBsMonth(bsYear, bsMonth) {
  const row = DATA[bsYear];
  if (!row || bsMonth < 1 || bsMonth > 12) return 0;
  return row[bsMonth - 1];
}

function daysInBsYear(bsYear) {
  const row = DATA[bsYear];
  if (!row) return 0;
  return row.reduce((a, b) => a + b, 0);
}

function sumYearDays(bsYear) {
  let total = 0;
  for (let y = BS_MIN_YEAR; y < bsYear; y += 1) {
    total += daysInBsYear(y);
  }
  return total;
}

export function isValidBsDate(bsYear, bsMonth, bsDay) {
  return (
    bsYear >= BS_MIN_YEAR &&
    bsYear <= BS_MAX_YEAR &&
    bsMonth >= 1 &&
    bsMonth <= 12 &&
    bsDay >= 1 &&
    bsDay <= daysInBsMonth(bsYear, bsMonth)
  );
}

export function bsToAd(bsYear, bsMonth, bsDay) {
  if (!isValidBsDate(bsYear, bsMonth, bsDay)) return null;
  let offset = sumYearDays(bsYear);
  for (let m = 1; m < bsMonth; m += 1) {
    offset += daysInBsMonth(bsYear, m);
  }
  offset += bsDay - 1;
  const date = new Date(EPOCH_AD.year, EPOCH_AD.month - 1, EPOCH_AD.day + offset);
  return { year: date.getFullYear(), month: date.getMonth() + 1, day: date.getDate() };
}

export function bsToAdDate(bsYear, bsMonth, bsDay) {
  const ad = bsToAd(bsYear, bsMonth, bsDay);
  if (!ad) return null;
  return new Date(ad.year, ad.month - 1, ad.day);
}

export function adToBs(adYear, adMonth, adDay) {
  const target = new Date(adYear, adMonth - 1, adDay);
  const epoch = new Date(EPOCH_AD.year, EPOCH_AD.month - 1, EPOCH_AD.day);
  let days = Math.round((target - epoch) / 86400000);
  if (days < 0) return null;
  let bsYear = BS_MIN_YEAR;
  while (bsYear <= BS_MAX_YEAR) {
    const yDays = daysInBsYear(bsYear);
    if (days < yDays) break;
    days -= yDays;
    bsYear += 1;
  }
  if (bsYear > BS_MAX_YEAR) return null;
  let bsMonth = 1;
  while (bsMonth <= 12) {
    const mDays = daysInBsMonth(bsYear, bsMonth);
    if (days < mDays) break;
    days -= mDays;
    bsMonth += 1;
  }
  if (bsMonth > 12) return null;
  return { year: bsYear, month: bsMonth, day: days + 1 };
}

export function weekdayOfBsDate(bsYear, bsMonth, bsDay) {
  const ad = bsToAdDate(bsYear, bsMonth, bsDay);
  if (!ad) return 0;
  return ad.getDay();
}
